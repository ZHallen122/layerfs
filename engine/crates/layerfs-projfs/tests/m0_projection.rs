//! M0: the standalone ProjFS spike. A plain directory is projected into a
//! virtualization root, with no LayerFS Store involved.
#![cfg(windows)]

mod support;

use layerfs_projfs::source::directory::DirectorySource;
use layerfs_projfs::sys;
use layerfs_projfs::{Change, Kind, Projection};
use std::path::PathBuf;
use std::sync::Arc;
use support::ops::{self, Op};
use support::{at, tree_digests, tree_state, Scratch};

struct Spike {
    home: Scratch,
    source: PathBuf,
    root: PathBuf,
    state: PathBuf,
}

impl Spike {
    fn new(label: &str) -> Self {
        let home = Scratch::new(label);
        let source = home.path().join("source");
        support::write_tree(&source);
        Self {
            root: home.path().join("root"),
            state: home.path().join("state"),
            source,
            home,
        }
    }
    fn mount(&self) -> Projection {
        Projection::mount(
            &self.root,
            &self.state,
            Arc::new(DirectorySource::new(&self.source)),
            0,
        )
        .expect("mount")
    }
}

fn change(path: &str, kind: Kind, directory: bool) -> Change {
    Change {
        path: path.to_owned(),
        kind,
        directory,
    }
}

#[test]
fn the_listing_matches_the_source_exactly() {
    let spike = Spike::new("m0-listing");
    let mounted = spike.mount();
    assert_eq!(tree_state(&spike.root), tree_state(&spike.source));
    assert_eq!(mounted.status().expect("status"), Vec::new());
    mounted.discard().expect("discard");
}

#[test]
fn every_file_reads_identical_bytes() {
    let spike = Spike::new("m0-bytes");
    let mounted = spike.mount();
    assert_eq!(tree_digests(&spike.root), tree_digests(&spike.source));
    // Reading hydrates; it is not a change.
    assert_eq!(mounted.status().expect("status"), Vec::new());
    mounted.discard().expect("discard");
}

#[test]
fn a_file_over_one_gibibyte_reads_identical_bytes() {
    use std::io::Write;
    let spike = Spike::new("m0-large");
    let large = spike.source.join("huge.bin");
    let length = (1u64 << 30) + 4321;
    {
        // 64 MiB of generated bytes, repeated with a different first byte.
        let block = support::pattern(7, 64 << 20);
        let mut file = std::fs::File::create(&large).expect("create");
        let mut written = 0u64;
        while written < length {
            let step = ((length - written) as usize).min(block.len());
            file.write_all(&[(written >> 26) as u8]).expect("write");
            file.write_all(&block[1..step]).expect("write");
            written += step as u64;
        }
    }
    assert_eq!(std::fs::metadata(&large).expect("metadata").len(), length);
    let mounted = spike.mount();
    let projected = spike.root.join("huge.bin");
    assert_eq!(
        std::fs::metadata(&projected).expect("metadata").len(),
        length
    );
    assert_eq!(
        support::file_digest(&projected),
        support::file_digest(&large)
    );
    mounted.discard().expect("discard");
}

#[test]
fn files_that_were_not_opened_are_not_hydrated() {
    let spike = Spike::new("m0-lazy");
    let mounted = spike.mount();
    // Listing the whole tree reads no file.
    let listed = tree_state(&spike.root);
    assert!(listed.contains_key("assets/large.bin"));
    assert_eq!(mounted.provider().served().reads, 0, "listing read no data");
    for (path, (directory, _, _)) in &listed {
        if *directory {
            continue;
        }
        let state = sys::disk_state(&at(&spike.root, path)).expect("state");
        assert!(
            state.is_none_or(|bits| bits & (sys::state::HYDRATED | sys::state::FULL) == 0),
            "{path} is hydrated after a listing: {state:?}"
        );
    }
    // Opening one file hydrates that file and no other.
    let read = std::fs::read(spike.root.join("README.md")).expect("read");
    assert_eq!(read, b"# fixture\n");
    let opened = sys::disk_state(&spike.root.join("README.md"))
        .expect("state")
        .expect("on disk");
    assert_ne!(opened & sys::state::HYDRATED, 0, "state {opened}");
    assert_eq!(opened & sys::state::FULL, 0, "state {opened}");
    let other = sys::disk_state(&at(&spike.root, "assets/large.bin")).expect("state");
    assert!(
        other.is_none_or(|bits| bits & (sys::state::HYDRATED | sys::state::FULL) == 0),
        "assets/large.bin: {other:?}"
    );
    mounted.discard().expect("discard");
}

/// Creates, modifies, deletes and renames files and directories, as
/// another process.
fn edit(spike: &Spike) {
    let root = &spike.root;
    ops::run(
        spike.home.path(),
        &[
            Op::Write(
                root.join("new.txt"),
                b"new file
"
                .to_vec(),
            ),
            Op::Mkdir(root.join("made")),
            Op::Write(
                at(root, "made/inside.txt"),
                b"inside
"
                .to_vec(),
            ),
            Op::Write(
                at(root, "src/main.rs"),
                b"fn main() { edited(); }
"
                .to_vec(),
            ),
            Op::Remove(root.join("empty.bin")),
            Op::RemoveTree(root.join("assets")),
            Op::Rename(at(root, "README.md"), at(root, "README.txt")),
            Op::Rename(root.join("made"), root.join("built")),
        ],
    );
}


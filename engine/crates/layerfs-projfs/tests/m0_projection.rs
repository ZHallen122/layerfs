#[test]
fn changes_in_the_root_never_change_the_source() {
    let spike = Spike::new("m0-isolation");
    let (state, digests) = (tree_state(&spike.source), tree_digests(&spike.source));
    let mounted = spike.mount();
    edit(&spike);
    assert_eq!(
        tree_state(&spike.source),
        state,
        "source names, sizes, times"
    );
    assert_eq!(tree_digests(&spike.source), digests, "source bytes");
    mounted.discard().expect("discard");
    assert_eq!(tree_state(&spike.source), state, "source after discard");
}

#[test]
fn status_reports_exactly_the_changes_made() {
    let spike = Spike::new("m0-status");
    let mounted = spike.mount();
    edit(&spike);
    let expected = vec![
        change(
            "README.txt",
            Kind::Renamed {
                from: "README.md".to_owned(),
            },
            false,
        ),
        change("assets", Kind::Deleted, true),
        change("built", Kind::Added, true),
        change("built/inside.txt", Kind::Added, false),
        change("empty.bin", Kind::Deleted, false),
        change("new.txt", Kind::Added, false),
        change("src/main.rs", Kind::Modified, false),
    ];
    assert_eq!(mounted.status().expect("status"), expected);
    // The view an application sees is the source with those changes.
    let seen = tree_state(&spike.root);
    for gone in [
        "README.md",
        "empty.bin",
        "assets",
        "assets/large.bin",
        "made",
    ] {
        assert!(!seen.contains_key(gone), "{gone} is still listed");
    }
    for present in [
        "README.txt",
        "new.txt",
        "built/inside.txt",
        "docs",
        "locked/read-only.txt",
    ] {
        assert!(seen.contains_key(present), "{present} is not listed");
    }
    mounted.discard().expect("discard");
}

#[test]
fn a_scan_of_the_disk_finds_the_changes_without_the_journal() {
    let spike = Spike::new("m0-rescan");
    let mounted = spike.mount();
    edit(&spike);
    mounted.unmount();
    // The provider is gone and its journal is thrown away, as after a kill
    // that lost every notification.
    std::fs::remove_file(spike.state.join("journal.log")).expect("journal");
    let (resumed, found) = Projection::resume(
        &spike.root,
        &spike.state,
        Arc::new(DirectorySource::new(&spike.source)),
        0,
    )
    .expect("resume");
    assert!(found > 0, "the scan found changed paths");
    // Without notifications a rename is a deletion and an addition.
    let expected = vec![
        change("README.md", Kind::Deleted, false),
        change("README.txt", Kind::Added, false),
        change("assets", Kind::Deleted, true),
        change("built", Kind::Added, true),
        change("built/inside.txt", Kind::Added, false),
        change("empty.bin", Kind::Deleted, false),
        change("new.txt", Kind::Added, false),
        change("src/main.rs", Kind::Modified, false),
    ];
    assert_eq!(resumed.status().expect("status"), expected);
    resumed.discard().expect("discard");
}

#[test]
fn discard_leaves_no_trace_and_a_fresh_mount_shows_the_original() {
    let spike = Spike::new("m0-discard");
    let original = tree_state(&spike.source);
    let mounted = spike.mount();
    edit(&spike);
    mounted.discard().expect("discard");
    assert!(!spike.root.exists(), "the root is gone");
    assert!(!spike.state.exists(), "the state is gone");
    let again = spike.mount();
    assert_eq!(tree_state(&spike.root), original);
    assert_eq!(tree_digests(&spike.root), tree_digests(&spike.source));
    assert_eq!(again.status().expect("status"), Vec::new());
    again.discard().expect("discard");
    let _ = &spike.home;
}

/// ProjFS limitation, recorded as UNSUPPORTED: the kernel refuses to rename
/// a directory that is projected (a placeholder), whether or not its content
/// was read. A directory created locally renames normally (see `edit`).
#[test]
fn renaming_a_projected_directory_is_refused_by_projfs() {
    const NOT_SUPPORTED: i32 = 50;
    let spike = Spike::new("m0-dir-rename");
    let before = tree_state(&spike.source);
    let mounted = spike.mount();
    let never_opened = ops::attempt(
        spike.home.path(),
        &[Op::Rename(
            spike.root.join("docs"),
            spike.root.join("documents"),
        )],
    );
    assert_eq!(never_opened[0].clone().map_err(|e| e.0), Err(NOT_SUPPORTED));
    // Reading everything below it does not make it renameable.
    let _ = tree_digests(&spike.root);
    let read = ops::attempt(
        spike.home.path(),
        &[Op::Rename(
            spike.root.join("src"),
            spike.root.join("source-code"),
        )],
    );
    assert_eq!(read[0].clone().map_err(|e| e.0), Err(NOT_SUPPORTED));
    assert_eq!(mounted.status().expect("status"), Vec::new());
    assert_eq!(tree_state(&spike.root), before, "the view is unchanged");
    assert_eq!(tree_state(&spike.source), before, "the source is unchanged");
    mounted.discard().expect("discard");
}
